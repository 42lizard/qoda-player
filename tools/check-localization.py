#!/usr/bin/env python3
"""Validate shipped catalogs and regenerate the QML JavaScript asset explicitly."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PLACEHOLDER = re.compile(r'%[1-9][0-9]*|\{[^{}]*\}')


def unique(pairs):
    result = {}
    for key, value in pairs:
        assert key not in result, f'Duplicate catalog key: {key}'
        result[key] = value
    return result


def generated(messages):
    return '.pragma library\n// Generated by tools/check-localization.py --write.\nvar messages = ' + json.dumps(messages, ensure_ascii=False, indent=2, sort_keys=True) + ';\n'


def check(write=False):
    directory = ROOT / 'ui/i18n'
    messages = json.loads((directory / 'de.json').read_text(), object_pairs_hook=unique)
    assert messages and all(isinstance(k, str) and isinstance(v, str) and v.strip() for k, v in messages.items())
    for source, translated in messages.items():
        assert sorted(PLACEHOLDER.findall(source)) == sorted(PLACEHOLDER.findall(translated)), f'Changed placeholders: {source}'
    for path in (ROOT / 'ui').glob('*.qml'):
        for match in re.finditer(r'I18n\.(?:t|count)\("((?:[^"\\]|\\.)*)"', path.read_text()):
            source = json.loads('"' + match[1] + '"')
            assert source in messages, f'Missing translation: {path.name}: {source}'
        for match in re.finditer(r'I18n\.count\("(?:[^"\\]|\\.)*",\s*("(?:[^"\\]|\\.)*")', path.read_text()):
            assert json.loads(match[1]) in messages, f'Missing plural: {path.name}: {match[1]}'
    # Proper names, shortcuts and environment identifiers are intentionally opaque.
    opaque = {"HOME", "XDG_CONFIG_HOME", "XDG_RUNTIME_DIR", "Ctrl+K", "Escape", "Qoda", "QODA", "Qoda Player", "SoXR VHQ", "ReplayGain"}
    for path in (ROOT / 'ui').glob('*.qml'):
        for match in re.finditer(r'"(?:[^"\\]|\\.)*"', path.read_text()):
            source = json.loads(match[0])
            human = re.search('[a-zA-Z]', source) and (' ' in source or source[:1].isupper())
            assert not human or source in messages or source in opaque, f'Uncatalogued UI text: {path.name}: {source}'
    content = generated(messages)
    if write:
        (directory / 'German.js').write_text(content)
    assert (directory / 'German.js').read_text() == content, 'Regenerate German.js with --write'
    print(f'English source / German catalog: {len(messages)} messages; placeholders and generated asset verified')



def runtime():
    """Fresh Qt engines: verify actual locale inheritance, not a test override."""
    import os
    import subprocess
    import tempfile
    cases = [
        ({'LANG': 'de_DE.UTF-8'}, 'de'),
        ({'LANG': 'de_AT.UTF-8'}, 'de'),
        ({'LANG': 'de_CH.UTF-8'}, 'de'),
        ({'LANG': 'en_US.UTF-8'}, 'en'),
        ({'LANG': 'fr_FR.UTF-8'}, 'en'),
        ({'LANG': 'C'}, 'en'),
        ({'LANG': 'C.UTF-8'}, 'en'),
        ({'LANG': 'POSIX'}, 'en'),
        ({'LANG': 'C', 'LANGUAGE': 'de'}, 'de'),
        ({}, 'en'),
        ({'LANG': 'de_DE.UTF-8', 'LC_ALL': 'en_US.UTF-8'}, 'en'),
        ({'LANG': 'en_US.UTF-8', 'LC_MESSAGES': 'de_DE.UTF-8'}, 'de'),
        ({'LANG': 'de_DE.UTF-8', 'LANGUAGE': 'en:de'}, 'en'),
        ({'LANG': 'de_DE.UTF-8', 'LC_NUMERIC': 'en_US.UTF-8'}, 'de'),
    ]
    with tempfile.TemporaryDirectory(prefix='qoda-locales-') as directory:
        path = Path(directory) / 'tst_Environment.qml'
        for variables, expected in cases:
            env = {k: v for k, v in os.environ.items() if k != 'LANG' and k != 'LANGUAGE' and not k.startswith('LC_')}
            env.update(variables, QT_QPA_PLATFORM='offscreen', QT_QUICK_BACKEND='software')
            numeric = '1,5' if variables.get('LC_ALL', variables.get('LC_NUMERIC', variables.get('LANG', ''))).startswith(('de_DE', 'de_AT', 'fr_FR')) else '1.5'
            source = f"""import QtQuick
import QtTest
import {json.dumps((ROOT / 'ui').as_uri())} as Qoda
TestCase {{
    name: "LocaleEnvironment"
    function test_inherited() {{
        compare(Qoda.I18n.language, {json.dumps(expected)});
        compare(Qoda.I18n.t("Play"), {json.dumps('Abspielen' if expected == 'de' else 'Play')});
        compare(Qoda.I18n.number(1.5, 1), {json.dumps(numeric)});
    }}
}}
"""
            path.write_text(source)
            result = subprocess.run(['/usr/lib/qt6/bin/qmltestrunner', '-input', str(path)], env=env, text=True, capture_output=True, timeout=20)
            assert result.returncode == 0, f'Locale {variables}:\n{result.stdout}\n{result.stderr}'
    print(f'Qt locale environment selection: {len(cases)} fresh processes passed')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--runtime', action='store_true')
    args = parser.parse_args()
    check(args.write)
    if args.runtime:
        runtime()
